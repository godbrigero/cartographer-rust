//! Port of `cartographer/ground_truth/autogenerate_ground_truth_main.cc`.
//!
//! Semi-automatically generates ground truth data from a pose graph proto.

use std::process::ExitCode;

use cartographer::ground_truth::autogenerate_ground_truth::generate_ground_truth;
use cartographer::io::proto_stream_deserializer::deserialize_pose_graph_from_file;
use clap::{CommandFactory, Parser};
use prost::Message;

/// This program semi-automatically generates ground truth data from a
/// pose graph proto.
///
/// The input should contain a single trajectory and should have been
/// manually assessed to be correctly loop closed. Small local distortions
/// are acceptable if they are tiny compared to the errors we want to
/// assess using the generated ground truth data.
///
/// All loop closure constraints separated by long covered distance are
/// included in the output. Outliers are removed.
#[derive(Parser, Debug)]
#[command(name = "cartographer_autogenerate_ground_truth", verbatim_doc_comment)]
struct Flags {
    /// Proto stream file containing the pose graph used to generate ground
    /// truth data.
    #[arg(long = "pose_graph_filename", default_value = "")]
    pose_graph_filename: String,

    /// File to write the ground truth proto to.
    #[arg(long = "output_filename", default_value = "")]
    output_filename: String,

    /// Minimum covered distance in meters before a loop closure is
    /// considered a candidate for autogenerated ground truth.
    #[arg(long = "min_covered_distance", default_value_t = 100.)]
    min_covered_distance: f64,

    /// Distance in meters beyond which constraints are considered outliers.
    #[arg(long = "outlier_threshold_meters", default_value_t = 0.15)]
    outlier_threshold_meters: f64,

    /// Distance in radians beyond which constraints are considered outliers.
    #[arg(long = "outlier_threshold_radians", default_value_t = 0.02)]
    outlier_threshold_radians: f64,
}

/// Minimal logger printing to stderr (C++ `FLAGS_logtostderr = true`).
struct StderrLogger;

impl log::Log for StderrLogger {
    fn enabled(&self, metadata: &log::Metadata) -> bool {
        metadata.level() <= log::Level::Info
    }

    fn log(&self, record: &log::Record) {
        if self.enabled(record.metadata()) {
            let level = record.level().as_str().chars().next().unwrap_or('I');
            eprintln!("{level} {}] {}", record.target(), record.args());
        }
    }

    fn flush(&self) {}
}

static LOGGER: StderrLogger = StderrLogger;

fn run(
    pose_graph_filename: &str,
    output_filename: &str,
    min_covered_distance: f64,
    outlier_threshold_meters: f64,
    outlier_threshold_radians: f64,
) {
    log::info!("Reading pose graph from '{pose_graph_filename}'...");
    let pose_graph = deserialize_pose_graph_from_file(pose_graph_filename);

    log::info!("Autogenerating ground truth relations...");
    let ground_truth = generate_ground_truth(
        &pose_graph,
        min_covered_distance,
        outlier_threshold_meters,
        outlier_threshold_radians,
    );
    log::info!(
        "Writing {} relations to '{output_filename}'.",
        ground_truth.relation.len()
    );
    if let Err(e) = std::fs::write(output_filename, ground_truth.encode_to_vec()) {
        panic!("Check failed: output_stream Could not write ground truth data. ({e})");
    }
}

fn main() -> ExitCode {
    if log::set_logger(&LOGGER).is_ok() {
        log::set_max_level(log::LevelFilter::Info);
    }
    let flags = Flags::parse();

    if flags.pose_graph_filename.is_empty() || flags.output_filename.is_empty() {
        let _ = Flags::command().print_help();
        return ExitCode::FAILURE;
    }
    run(
        &flags.pose_graph_filename,
        &flags.output_filename,
        flags.min_covered_distance,
        flags.outlier_threshold_meters,
        flags.outlier_threshold_radians,
    );
    ExitCode::SUCCESS
}
