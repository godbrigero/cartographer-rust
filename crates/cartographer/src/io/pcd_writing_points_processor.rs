use nalgebra::Vector3;

use crate::common::lua_parameter_dictionary::LuaParameterDictionary;
use crate::io::color::{Uint8Color, to_uint8_color};
use crate::io::file_writer::{FileWriter, FileWriterFactory};
use crate::io::points_batch::PointsBatch;
use crate::io::points_processor::{FlushResult, PointsProcessor};

// Writes the PCD header claiming 'num_points' will follow it into
// 'output_file'.
fn write_binary_pcd_header(has_color: bool, num_points: i64, file_writer: &mut dyn FileWriter) {
    let color_header_field = if !has_color { "" } else { " rgb" };
    let color_header_type = if !has_color { "" } else { " U" };
    let color_header_size = if !has_color { "" } else { " 4" };
    let color_header_count = if !has_color { "" } else { " 1" };
    let out = format!(
        "# generated by Cartographer\n\
         VERSION .7\n\
         FIELDS x y z{color_header_field}\n\
         SIZE 4 4 4{color_header_size}\n\
         TYPE F F F{color_header_type}\n\
         COUNT 1 1 1{color_header_count}\n\
         WIDTH {num_points:015}\n\
         HEIGHT 1\n\
         VIEWPOINT 0 0 0 1 0 0 0\n\
         POINTS {num_points:015}\n\
         DATA binary\n"
    );
    // The C++ code ignores the result here.
    file_writer.write_header(out.as_bytes());
}

fn write_binary_pcd_point_coordinate(point: &Vector3<f32>, file_writer: &mut dyn FileWriter) {
    // RUST PORT NOTE: C++ memcpy's the host representation; we always write
    // little endian (identical on all supported hosts).
    let mut buffer = [0u8; 12];
    buffer[0..4].copy_from_slice(&point[0].to_le_bytes());
    buffer[4..8].copy_from_slice(&point[1].to_le_bytes());
    buffer[8..12].copy_from_slice(&point[2].to_le_bytes());
    assert!(
        file_writer.write(&buffer),
        "Check failed: file_writer->Write(buffer, 12)"
    );
}

fn write_binary_pcd_point_color(color: &Uint8Color, file_writer: &mut dyn FileWriter) {
    let buffer = [color[2], color[1], color[0], 0];
    assert!(
        file_writer.write(&buffer),
        "Check failed: file_writer->Write(buffer, 4)"
    );
}

/// Streams a PCD file to disk. The header is written in `flush`.
pub struct PcdWritingPointsProcessor {
    next: Box<dyn PointsProcessor>,
    num_points: i64,
    has_colors: bool,
    file_writer: Box<dyn FileWriter>,
}

impl PcdWritingPointsProcessor {
    /// Name of this processor in the Lua pipeline configuration.
    pub const CONFIGURATION_FILE_ACTION_NAME: &'static str = "write_pcd";

    /// Creates the processor writing into `file_writer`.
    pub fn new(file_writer: Box<dyn FileWriter>, next: Box<dyn PointsProcessor>) -> Self {
        Self {
            next,
            num_points: 0,
            has_colors: false,
            file_writer,
        }
    }

    /// Creates the processor writing to `filename`.
    pub fn from_dictionary(
        file_writer_factory: &FileWriterFactory,
        dictionary: &LuaParameterDictionary,
        next: Box<dyn PointsProcessor>,
    ) -> Box<Self> {
        Box::new(Self::new(
            file_writer_factory(&dictionary.get_string("filename")),
            next,
        ))
    }
}

impl PointsProcessor for PcdWritingPointsProcessor {
    fn process(&mut self, batch: Box<PointsBatch>) {
        if batch.points.is_empty() {
            self.next.process(batch);
            return;
        }

        if self.num_points == 0 {
            self.has_colors = !batch.colors.is_empty();
            write_binary_pcd_header(self.has_colors, 0, self.file_writer.as_mut());
        }
        for (i, point) in batch.points.iter().enumerate() {
            write_binary_pcd_point_coordinate(&point.position, self.file_writer.as_mut());
            // Note: like the C++ code, colors are written per batch, without
            // checking consistency with the header.
            if !batch.colors.is_empty() {
                write_binary_pcd_point_color(
                    &to_uint8_color(&batch.colors[i]),
                    self.file_writer.as_mut(),
                );
            }
            self.num_points += 1;
        }
        self.next.process(batch);
    }

    fn flush(&mut self) -> FlushResult {
        write_binary_pcd_header(self.has_colors, self.num_points, self.file_writer.as_mut());
        assert!(
            self.file_writer.close(),
            "Check failed: file_writer_->Close()"
        );

        match self.next.flush() {
            FlushResult::Finished => FlushResult::Finished,
            FlushResult::RestartStream => panic!(
                "PCD generation must be configured to occur after any stages that require \
                 multiple passes."
            ),
        }
    }
}

#[cfg(test)]
mod tests {
    use std::sync::{Arc, Mutex};

    use super::*;
    use crate::io::fake_file_writer::FakeFileWriter;
    use crate::io::null_points_processor::NullPointsProcessor;
    use crate::sensor::rangefinder_point::RangefinderPoint;

    fn run(batches: Vec<PointsBatch>) -> Vec<u8> {
        let content = Arc::new(Mutex::new(Vec::new()));
        let mut processor = PcdWritingPointsProcessor::new(
            Box::new(FakeFileWriter::new("test.pcd", Arc::clone(&content))),
            Box::new(NullPointsProcessor::new()),
        );
        for batch in batches {
            processor.process(Box::new(batch));
        }
        assert_eq!(processor.flush(), FlushResult::Finished);
        content.lock().unwrap().clone()
    }

    fn header(has_color: bool, n: i64) -> String {
        let (field, size, ty, count) = if has_color {
            (" rgb", " 4", " U", " 1")
        } else {
            ("", "", "", "")
        };
        format!(
            "# generated by Cartographer\nVERSION .7\nFIELDS x y z{field}\nSIZE 4 4 4{size}\n\
             TYPE F F F{ty}\nCOUNT 1 1 1{count}\nWIDTH {n:015}\nHEIGHT 1\n\
             VIEWPOINT 0 0 0 1 0 0 0\nPOINTS {n:015}\nDATA binary\n"
        )
    }

    #[test]
    fn golden_output_with_colors() {
        let batch = PointsBatch {
            points: vec![
                RangefinderPoint {
                    position: Vector3::new(1.0, -2.0, 0.5),
                },
                RangefinderPoint {
                    position: Vector3::new(0.0, 3.25, -1.0),
                },
            ],
            colors: vec![[1.0, 0.5, 0.0], [0.0, 0.0, 1.0]],
            ..Default::default()
        };
        let output = run(vec![PointsBatch::default(), batch]);
        let mut expected = header(true, 2).into_bytes();
        for (p, c) in [
            ([1.0f32, -2.0, 0.5], [0u8, 128, 255, 0]),
            ([0.0, 3.25, -1.0], [255, 0, 0, 0]),
        ] {
            for v in p {
                expected.extend_from_slice(&v.to_le_bytes());
            }
            expected.extend_from_slice(&c);
        }
        assert_eq!(output, expected);
        assert!(String::from_utf8_lossy(&output).starts_with(
            "# generated by Cartographer\nVERSION .7\nFIELDS x y z rgb\nSIZE 4 4 4 4\n\
                 TYPE F F F U\nCOUNT 1 1 1 1\nWIDTH 000000000000002\nHEIGHT 1\n\
                 VIEWPOINT 0 0 0 1 0 0 0\nPOINTS 000000000000002\nDATA binary\n"
        ));
    }

    #[test]
    fn golden_output_without_points() {
        assert_eq!(run(vec![]), header(false, 0).into_bytes());
    }
}
