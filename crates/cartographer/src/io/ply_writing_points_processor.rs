// Writes the PLY header claiming 'num_points' will follow it into
// 'output_file'.
fn write_binary_ply_header(
    has_color: bool,
    has_intensities: bool,
    comments: &[String],
    num_points: i64,
    file_writer: &mut dyn FileWriter,
) {
    let color_header = if !has_color {
        ""
    } else {
        "property uchar red\nproperty uchar green\nproperty uchar blue\n"
    };
    let intensity_header = if !has_intensities {
        ""
    } else {
        "property float intensity\n"
    };
    let mut out =
        String::from("ply\nformat binary_little_endian 1.0\ncomment generated by Cartographer\n");
    for comment in comments {
        out.push_str("comment ");
        out.push_str(comment);
        out.push('\n');
    }
    out.push_str(&format!(
        "element vertex {num_points:015}\n\
         property float x\n\
         property float y\n\
         property float z\n\
         {color_header}{intensity_header}end_header\n"
    ));
    assert!(
        file_writer.write_header(out.as_bytes()),
        "Check failed: file_writer->WriteHeader(out.data(), out.size())"
    );
}

fn write_binary_ply_point_coordinate(point: &Vector3<f32>, file_writer: &mut dyn FileWriter) {
    // RUST PORT NOTE: the C++ code ignores endianness (TODO(sirver)); PLY
    // declares binary_little_endian, which we always write.
    let mut buffer = [0u8; 12];
    buffer[0..4].copy_from_slice(&point[0].to_le_bytes());
    buffer[4..8].copy_from_slice(&point[1].to_le_bytes());
    buffer[8..12].copy_from_slice(&point[2].to_le_bytes());
    assert!(
        file_writer.write(&buffer),
        "Check failed: file_writer->Write(buffer, 12)"
    );
}

fn write_binary_intensity(intensity: f32, file_writer: &mut dyn FileWriter) {
    assert!(
        file_writer.write(&intensity.to_le_bytes()),
        "Check failed: file_writer->Write(intensity)"
    );
}

fn write_binary_ply_point_color(color: &Uint8Color, file_writer: &mut dyn FileWriter) {
    assert!(
        file_writer.write(color),
        "Check failed: file_writer->Write(color)"
    );
}

/// Streams a PLY file to disk. The header is written in `flush`.
pub struct PlyWritingPointsProcessor {
    next: Box<dyn PointsProcessor>,
    comments: Vec<String>,
    num_points: i64,
    has_colors: bool,
    // RUST PORT NOTE: uninitialized in the C++ constructor (UB when flushing
    // without any points); initialized to false here.
    has_intensities: bool,
    file: Box<dyn FileWriter>,
}

impl PlyWritingPointsProcessor {
    /// Name of this processor in the Lua pipeline configuration.
    pub const CONFIGURATION_FILE_ACTION_NAME: &'static str = "write_ply";

    /// Creates the processor writing into `file_writer`, adding `comments` to
    /// the header.
    pub fn new(
        file_writer: Box<dyn FileWriter>,
        comments: &[String],
        next: Box<dyn PointsProcessor>,
    ) -> Self {
        Self {
            next,
            comments: comments.to_vec(),
            num_points: 0,
            has_colors: false,
            has_intensities: false,
            file: file_writer,
        }
    }

    /// Creates the processor writing to `filename` (no comments).
    pub fn from_dictionary(
        file_writer_factory: &FileWriterFactory,
        dictionary: &LuaParameterDictionary,
        next: Box<dyn PointsProcessor>,
    ) -> Box<Self> {
        Box::new(Self::new(
            file_writer_factory(&dictionary.get_string("filename")),
            &[],
            next,
        ))
    }
}

impl PointsProcessor for PlyWritingPointsProcessor {
    fn process(&mut self, batch: Box<PointsBatch>) {
        if batch.points.is_empty() {
            self.next.process(batch);
            return;
        }

        if self.num_points == 0 {
            self.has_colors = !batch.colors.is_empty();
            self.has_intensities = !batch.intensities.is_empty();
            write_binary_ply_header(
                self.has_colors,
                self.has_intensities,
                &self.comments,
                0,
                self.file.as_mut(),
            );
        }
        if self.has_colors {
            assert_eq!(
                batch.points.len(),
                batch.colors.len(),
                "First PointsBatch had colors, but encountered one without. frame_id: {}",
                batch.frame_id
            );
        }
        if self.has_intensities {
            assert_eq!(
                batch.points.len(),
                batch.intensities.len(),
                "First PointsBatch had intensities, but encountered one without. frame_id: {}",
                batch.frame_id
            );
        }
        for (i, point) in batch.points.iter().enumerate() {
            write_binary_ply_point_coordinate(&point.position, self.file.as_mut());
            if self.has_colors {
                write_binary_ply_point_color(&to_uint8_color(&batch.colors[i]), self.file.as_mut());
            }
            if self.has_intensities {
                write_binary_intensity(batch.intensities[i], self.file.as_mut());
            }
            self.num_points += 1;
        }
        self.next.process(batch);
    }

    fn flush(&mut self) -> FlushResult {
        write_binary_ply_header(
            self.has_colors,
            self.has_intensities,
            &self.comments,
            self.num_points,
            self.file.as_mut(),
        );
        assert!(self.file.close(), "Closing PLY file_writer failed.");

        match self.next.flush() {
            FlushResult::Finished => FlushResult::Finished,
            FlushResult::RestartStream => panic!(
                "PLY generation must be configured to occur after any stages that require \
                 multiple passes."
            ),
        }
    }
}

#[cfg(test)]
mod tests {
    use std::sync::{Arc, Mutex};

    use super::*;
    use crate::io::fake_file_writer::FakeFileWriter;
    use crate::io::null_points_processor::NullPointsProcessor;
    use crate::sensor::rangefinder_point::RangefinderPoint;

    fn run(comments: &[String], batches: Vec<PointsBatch>) -> Vec<u8> {
        let content = Arc::new(Mutex::new(Vec::new()));
        let mut processor = PlyWritingPointsProcessor::new(
            Box::new(FakeFileWriter::new("test.ply", Arc::clone(&content))),
            comments,
            Box::new(NullPointsProcessor::new()),
        );
        for batch in batches {
            processor.process(Box::new(batch));
        }
        assert_eq!(processor.flush(), FlushResult::Finished);
        content.lock().unwrap().clone()
    }

    fn points() -> Vec<RangefinderPoint> {
        vec![
            RangefinderPoint {
                position: Vector3::new(1.0, 2.0, 3.0),
            },
            RangefinderPoint {
                position: Vector3::new(-0.5, 0.25, 1e-3),
            },
        ]
    }

    #[test]
    fn golden_output_with_colors_and_intensities() {
        let batch = PointsBatch {
            points: points(),
            colors: vec![[1.0, 0.0, 0.2], [0.0, 1.0, 0.0]],
            intensities: vec![10.0, 255.5],
            ..Default::default()
        };
        let output = run(&["first".to_string(), "second".to_string()], vec![batch]);
        let mut expected = b"ply\nformat binary_little_endian 1.0\n\
            comment generated by Cartographer\ncomment first\ncomment second\n\
            element vertex 000000000000002\nproperty float x\nproperty float y\n\
            property float z\nproperty uchar red\nproperty uchar green\n\
            property uchar blue\nproperty float intensity\nend_header\n"
            .to_vec();
        for (p, c, i) in [
            ([1.0f32, 2.0, 3.0], [255u8, 0, 51], 10.0f32),
            ([-0.5, 0.25, 1e-3], [0, 255, 0], 255.5),
        ] {
            for v in p {
                expected.extend_from_slice(&v.to_le_bytes());
            }
            expected.extend_from_slice(&c);
            expected.extend_from_slice(&i.to_le_bytes());
        }
        assert_eq!(output, expected);
    }

    #[test]
    fn golden_output_plain() {
        let batch = PointsBatch {
            points: points(),
            ..Default::default()
        };
        let output = run(&[], vec![batch]);
        let mut expected = b"ply\nformat binary_little_endian 1.0\n\
            comment generated by Cartographer\nelement vertex 000000000000002\n\
            property float x\nproperty float y\nproperty float z\nend_header\n"
            .to_vec();
        for p in [[1.0f32, 2.0, 3.0], [-0.5, 0.25, 1e-3]] {
            for v in p {
                expected.extend_from_slice(&v.to_le_bytes());
            }
        }
        assert_eq!(output, expected);
    }

    #[test]
    fn empty_output_has_header_only() {
        let output = run(&[], vec![]);
        assert_eq!(
            output,
            b"ply\nformat binary_little_endian 1.0\ncomment generated by Cartographer\n\
              element vertex 000000000000000\nproperty float x\nproperty float y\n\
              property float z\nend_header\n"
                .to_vec()
        );
    }

    #[test]
    #[should_panic(expected = "First PointsBatch had colors")]
    fn inconsistent_colors_panic() {
        let with_colors = PointsBatch {
            points: points(),
            colors: vec![[1.0, 0.0, 0.0]; 2],
            ..Default::default()
        };
        let without_colors = PointsBatch {
            points: points(),
            ..Default::default()
        };
        run(&[], vec![with_colors, without_colors]);
    }
}
